@props([
    'title',
    'number',
    'date',
    'status' => null,
    'statusTone' => 'badge-ghost',
    'partyLabel',
    'partyName',
    'partyLines' => [],
    'meta' => [],
    'notes' => null,
    'signatures' => [],
])

@php
    $companyName = \App\Models\Setting::get('company_name', config('app.name'));
    $farm = \App\Models\Farm::query()->orderBy('name')->first();
    $companyAddress = collect([
        $farm?->address,
        collect([$farm?->village, $farm?->district, $farm?->regency, $farm?->province, $farm?->postal_code])
            ->filter()
            ->implode(', '),
    ])->filter()->implode(', ');
@endphp

{{--
    A formal paper document rather than a printed application page.

    It is deliberately self-contained: letterhead, addressee, metadata, lines,
    totals and signatures all live inside one white A4-width sheet, so printing
    produces a document that can be filed or sent to a customer or supplier.
--}}
<article class="document-paper mx-auto w-full max-w-[210mm] border border-slate-200 bg-white px-5 py-6 text-slate-900 shadow-sm sm:px-10 sm:py-10 print:max-w-none print:border-0 print:p-0 print:shadow-none">
    <header class="flex flex-col gap-5 border-b-2 border-slate-900 pb-5 sm:flex-row sm:items-start sm:justify-between">
        <div class="flex items-start gap-3">
            <img src="{{ asset('images/logo-mark-black.png') }}" alt="" class="h-12 w-12 shrink-0 object-contain">
            <div class="min-w-0">
                <p class="text-lg font-semibold leading-tight">{{ $companyName }}</p>
                @if ($companyAddress !== '')
                    <p class="mt-1 max-w-xs text-xs leading-relaxed text-slate-600">{{ $companyAddress }}</p>
                @endif
                @if ($farm?->phone)
                    <p class="mt-0.5 text-xs text-slate-600">Tel. {{ $farm->phone }}</p>
                @endif
            </div>
        </div>

        <div class="shrink-0 sm:text-right">
            <p class="text-xs font-semibold uppercase tracking-[0.18em] text-slate-500">{{ $title }}</p>
            <p class="mt-1 font-mono text-lg font-semibold">{{ $number }}</p>
            <p class="mt-1 text-xs text-slate-600">{{ $date }}</p>
            @if ($status)
                <div class="mt-2 sm:flex sm:justify-end">
                    <x-badge :label="$status" :class="$statusTone" />
                </div>
            @endif
        </div>
    </header>

    <section class="mt-6 grid gap-6 sm:grid-cols-2">
        <div>
            <p class="text-[0.65rem] font-semibold uppercase tracking-wider text-slate-500">{{ $partyLabel }}</p>
            <p class="mt-1 text-sm font-semibold">{{ $partyName }}</p>
            @foreach ($partyLines as $line)
                <p class="text-xs leading-relaxed text-slate-600">{{ $line }}</p>
            @endforeach
        </div>

        <dl class="grid grid-cols-[auto_1fr] gap-x-4 gap-y-1 text-xs sm:justify-self-end">
            @foreach ($meta as $label => $value)
                <dt class="text-slate-500">{{ $label }}</dt>
                <dd class="text-right font-medium text-slate-800">{{ $value }}</dd>
            @endforeach
        </dl>
    </section>

    <section class="mt-6 overflow-x-auto print:overflow-visible">
        {{ $lines }}
    </section>

    <section class="mt-5 flex flex-col gap-5 sm:flex-row sm:items-start sm:justify-between">
        <div class="max-w-sm text-xs leading-relaxed text-slate-600">
            @if ($notes)
                <p class="text-[0.65rem] font-semibold uppercase tracking-wider text-slate-500">{{ __('Notes') }}</p>
                <p class="mt-1 whitespace-pre-line">{{ $notes }}</p>
            @endif
        </div>

        <div class="w-full sm:max-w-xs">
            {{ $totals }}
        </div>
    </section>

    @if ($signatures !== [])
        <footer class="mt-10 grid gap-8 border-t border-slate-200 pt-6 sm:grid-cols-2">
            @foreach ($signatures as $signature)
                <div>
                    <p class="text-[0.65rem] font-semibold uppercase tracking-wider text-slate-500">{{ $signature['label'] }}</p>
                    <div class="mt-12 border-b border-slate-400"></div>
                    <p class="mt-1 text-sm font-semibold">{{ $signature['name'] ?? ' ' }}</p>
                    @if (! empty($signature['role']))
                        <p class="text-xs text-slate-500">{{ $signature['role'] }}</p>
                    @endif
                </div>
            @endforeach
        </footer>
    @endif

    <p class="mt-6 border-t border-slate-200 pt-3 text-[0.65rem] leading-relaxed text-slate-400">
        {{ __('This document was generated by FARM.') }}
    </p>
</article>
