<?php

namespace Tests\Feature;

use App\Enums\InvoiceStatus;
use App\Models\GoodsReceipt;
use App\Models\Invoice;
use App\Models\PurchaseOrder;
use App\Models\SalesOrder;
use App\Models\User;
use Database\Seeders\DatabaseSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class DocumentTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();

        $this->seed(DatabaseSeeder::class);
    }

    public function test_invoice_sales_order_purchase_order_and_receipt_render_as_formal_documents(): void
    {
        $owner = User::query()->where('role', 'owner')->firstOrFail();

        $documents = [
            route('invoices.document', Invoice::query()->firstOrFail()) => Invoice::query()->firstOrFail()->invoice_number,
            route('sales-orders.document', SalesOrder::query()->firstOrFail()) => SalesOrder::query()->firstOrFail()->so_number,
            route('purchase-orders.document', PurchaseOrder::query()->firstOrFail()) => PurchaseOrder::query()->firstOrFail()->po_number,
            route('goods-receipts.document', GoodsReceipt::query()->firstOrFail()) => GoodsReceipt::query()->firstOrFail()->receipt_number,
        ];

        foreach ($documents as $url => $number) {
            $this->actingAs($owner)
                ->get($url)
                ->assertOk()
                ->assertSee('document-paper', false)
                ->assertSee('document-toolbar', false)
                ->assertSee($number)
                ->assertSee(__('This document was generated by FARM.'))
                ->assertDontSee('app-drawer', false);
        }
    }

    public function test_show_pages_link_to_their_documents_and_use_clear_invoice_actions(): void
    {
        $owner = User::query()->where('role', 'owner')->firstOrFail();
        $invoice = Invoice::query()->firstOrFail();
        $invoice->forceFill(['paid_amount' => 0, 'status' => InvoiceStatus::Unpaid])->save();
        $salesOrder = SalesOrder::query()->firstOrFail();

        $this->actingAs($owner)
            ->get(route('invoices.show', $invoice))
            ->assertOk()
            ->assertSee(route('invoices.document', $invoice), false)
            ->assertSee(__('Record invoice payment'));

        $this->actingAs($owner)
            ->get(route('sales-orders.show', $salesOrder))
            ->assertOk()
            ->assertSee(route('sales-orders.document', $salesOrder), false)
            ->assertSee(__('Print document'));
    }
}
